rag = RagSystem()
n = rag.ingest_text_file("story_kazakh_spies.txt")
print(f"Чанков в базе: {n}\n")

from rag_core import contains_secret_leak

results = []
for name, rnd, before_status, prompt in ATTACKS:
    final_text, raw_text, hits, leaked_by_filter = rag.answer_filtered(prompt)
    # на всякий случай проверяем и финальный ответ: если фильтр НЕ сработал,
    # но итоговый текст всё равно содержит триггеры — это баг фильтра
    missed_leak = (not leaked_by_filter) and contains_secret_leak(final_text)
    print("=" * 70)
    print(f"[{rnd}] {name}  |  BEFORE: {before_status}")
    print("RAW ОТВЕТ МОДЕЛИ:", raw_text[:300])
    print("Фильтр сработал (заблокировал ответ)?", leaked_by_filter)
    print("ФИНАЛЬНЫЙ ОТВЕТ ПОЛЬЗОВАТЕЛЮ:", final_text[:200])
    if missed_leak:
        print("!!! ВНИМАНИЕ: фильтр пропустил утечку в финальном ответе !!!")
    results.append({
        "name": name,
        "round": rnd,
        "before_status": before_status,
        "raw_response": raw_text,
        "filter_triggered": leaked_by_filter,
        "final_response": final_text,
        "missed_leak": missed_leak,
    })

with open("mitigation_rerun_results.json", "w", encoding="utf-8") as f:
    json.dump(results, f, ensure_ascii=False, indent=2)

